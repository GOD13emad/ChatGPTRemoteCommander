import test from 'node:test';
const EPOCH='bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb';
import assert from 'node:assert/strict';
import {createHmac} from 'node:crypto';
import {createMcpEventsCallbackVerifier} from '../src/delivery-mcp-callback-verifier.mjs';
import {createAuthenticatedMcpEventSubscriptions} from '../src/delivery-mcp-subscriptions.mjs';
import {DELIVERY_MCP_EVENT} from '../src/delivery-mcp-events.mjs';

const secret='whsec_'+Buffer.alloc(32,9).toString('base64');
const subscriptionId='sub_'+'a'.repeat(64);
const url='https://callbacks.example.net/chatgpt';
const challenge='A'.repeat(32);
const now=()=>Date.UTC(2026,10,6,2,0,1);
function fixture(overrides={}){
  const requests=[];
  const postVerifiedHttps=async request=>{
    requests.push(request);
    return {status:200,body:JSON.stringify({challenge:JSON.parse(request.body).challenge})};
  };
  const verifier=createMcpEventsCallbackVerifier({
    postVerifiedHttps,now,newMessageId:()=> 'b'.repeat(32),...overrides
  });
  return {requests,verifier,postVerifiedHttps};
}
test('signed verification uses exact body bytes and owner-scoped subscription header',async()=>{
  const f=fixture();
  const proof=await f.verifier.verifyCallback({url,secret,challenge,subscriptionId});
  assert.deepEqual(proof,{verified:true,challenge});
  assert.equal(f.requests.length,1);
  const req=f.requests[0],headers=req.headers;
  assert.equal(req.noRedirects,true);
  assert.equal(req.timeoutMs,5000);
  assert.equal(req.url,url);
  assert.equal(req.body,JSON.stringify({type:'verification',challenge}));
  assert.equal(headers['webhook-id'],'msg_verification_'+'b'.repeat(32));
  assert.equal(headers['webhook-timestamp'],'1793930401');
  assert.equal(headers['X-MCP-Subscription-Id'],subscriptionId);
  assert.equal(headers['webhook-signature'],'v1,'+createHmac('sha256',Buffer.alloc(32,9))
    .update(headers['webhook-id']+'.'+headers['webhook-timestamp']+'.'+req.body).digest('base64'));
  // Golden vector generated by the Standard Webhooks reference library v1.1.1 (MIT).
  assert.equal(headers['webhook-signature'],
    'v1,kJmrIS2E/S2I0Oj5llx75mru5lmGR72u70c+wJgeVJk=');
  assert.equal(JSON.stringify(proof).includes(secret),false);
});
test('callback echo mismatch, non-2xx and oversized response are denied',async()=>{
  const responses=[
    {status:200,body:JSON.stringify({challenge:'Z'.repeat(32)})},
    {status:307,body:JSON.stringify({challenge})},
    {status:503,body:JSON.stringify({challenge})},
    {status:200,body:'BAD_JSON'},
    {status:200,body:' '.repeat(8193)}
  ];
  for(const response of responses){
    const f=fixture({postVerifiedHttps:async()=>response});
    const error=await f.verifier.verifyCallback({url,secret,challenge,subscriptionId})
      .then(()=>null,value=>value);
    assert.equal(error?.code,'DELIVERY_CALLBACK_UNVERIFIED');
    assert.deepEqual(error.jsonRpcError,{
      code:-32015,message:'Callback endpoint verification failed',
      data:{reason:'challenge_failed'}
    });
  }
});
test('HTTPS failure and invalid challenge cannot create a verification proof',async()=>{
  const f=fixture({postVerifiedHttps:async()=>{throw Error('TLS_HANDSHAKE_FAILED');}});
  const unreachable=await f.verifier.verifyCallback({url,secret,challenge,subscriptionId})
    .then(()=>null,value=>value);
  assert.equal(unreachable?.code,'DELIVERY_CALLBACK_NOT_REACHABLE');
  assert.deepEqual(unreachable.jsonRpcError,{
    code:-32015,message:'Callback endpoint verification failed',
    data:{reason:'unreachable'}
  });
  const timed=fixture({postVerifiedHttps:async()=>{
    throw Object.assign(new Error('deadline exceeded'),{code:'DELIVERY_EGRESS_TIMEOUT'});
  }});
  const timeout=await timed.verifier.verifyCallback({url,secret,challenge,subscriptionId})
    .then(()=>null,value=>value);
  assert.equal(timeout?.code,'DELIVERY_CALLBACK_NOT_REACHABLE');
  assert.equal(timeout.jsonRpcError.code,-32015);
  assert.equal(timeout.jsonRpcError.data.reason,'timeout');
  await assert.rejects(()=>f.verifier.verifyCallback({
    url,secret,challenge:'abc',subscriptionId
  }),/DELIVERY_CALLBACK_INPUT_INVALID/);
  await assert.rejects(()=>f.verifier.verifyCallback({
    url,secret:'whsec_invalid',challenge,subscriptionId
  }),/DELIVERY_CALLBACK_SECRET_INVALID/);
  assert.equal(f.requests.length,0);
});
test('signed callback challenge is required before a subscription can be persisted',async()=>{
  const caller={hostId:'host1',principalId:'alice',profileId:'profile1',conversationId:'chat1'};
  const binding={...caller,correlationId:'route1',bindingId:EPOCH};
  const rows=[],requests=[];
  const verifier=createMcpEventsCallbackVerifier({
    now,newMessageId:()=> 'f'.repeat(32),
    postVerifiedHttps:async request=>{
      requests.push(request);
      return {status:200,body:JSON.stringify({challenge:JSON.parse(request.body).challenge})};
    }
  });
  const manager=createAuthenticatedMcpEventSubscriptions({
    observeCaller:async()=>caller,resolveBinding:async()=>binding,
    authorizeSubscription:async()=>true,
    verifyCallback:verifier.verifyCallback,
    sealSecret:async()=> 'sealed:opaque-key',
    secureStore:{upsert:async row=>rows.push(row),remove:async()=>{}},now
  });
  const created=await manager.subscribe({
    name:DELIVERY_MCP_EVENT,arguments:{},cursor:null,
    delivery:{mode:'webhook',url,secret}
  });
  assert.equal(rows.length,1);
  assert.equal(requests.length,1);
  assert.equal(requests[0].headers['X-MCP-Subscription-Id'],created.id);
  assert.equal(rows[0].id,created.id);
  assert.equal(rows[0].sealedSecret,'sealed:opaque-key');
});
test('failed verification creates no durable subscription or leaked secret',async()=>{
  const caller={hostId:'host1',principalId:'alice',profileId:'profile1',conversationId:'chat1'};
  const verifier=createMcpEventsCallbackVerifier({
    postVerifiedHttps:async()=>({status:200,body:'{"challenge":"WRONG"}'})
  });
  let writes=0;
  const manager=createAuthenticatedMcpEventSubscriptions({
    observeCaller:async()=>caller,
    resolveBinding:async()=>({...caller,correlationId:'route1',bindingId:EPOCH}),
    authorizeSubscription:async()=>true,
    verifyCallback:verifier.verifyCallback,
    sealSecret:async()=>{throw Error('SECRET_SHOULD_NOT_BE_SEALED');},
    secureStore:{upsert:async()=>{writes++;},remove:async()=>{}}
  });
  await assert.rejects(()=>manager.subscribe({
    name:DELIVERY_MCP_EVENT,arguments:{},
    delivery:{mode:'webhook',url,secret}
  }),/DELIVERY_CALLBACK_UNVERIFIED/);
  assert.equal(writes,0);
});
